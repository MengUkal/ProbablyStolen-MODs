# gen-patch-targets.ps1 — 从反编译源码提取引用 UnityEngine.Input 的方法清单
$dir = "D:\深空当铺MOD\游戏反编译\Assembly-CSharp"
$outFile = "D:\深空当铺MOD\GamepadPoc\Patches\PatchTargets.g.cs"
$patterns = @("Input\.mousePosition","Input\.GetMouseButton","Input\.GetKeyDown","Input\.GetKeyUp","Input\.GetKey\(","Input\.GetAxis","Input\.mouseScrollDelta","Input\.anyKey","Input\.GetButtonDown","Input\.GetButton\(")
$targets = [System.Collections.Generic.SortedSet[string]]::new()
$unparsed = 0

foreach ($f in (Get-ChildItem -LiteralPath $dir -Filter *.cs)) {
    $lines = Get-Content -LiteralPath $f.FullName
    for ($i = 0; $i -lt $lines.Count; $i++) {
        if ($lines[$i] -notmatch ($patterns -join '|')) { continue }
        $sig = $null
        for ($j = $i; $j -ge 0; $j--) {
            $L = $lines[$j]
            if ($L -match '^\t[A-Za-z].*$' -and ($L -match '\(' -or $L -match '=>')) { $sig = $L.Trim(); break }
            if ($L -match '^\t\}\s*$') { break }
        }
        if (-not $sig) { $unparsed++; continue }
        if ($sig -match '(?:public|private|protected|internal)[\w<>\[\], ]*\s+([\w<>]+)\s*\(([^)]*)\)') {
            $mname = $Matches[1]
            $params = $Matches[2].Trim()
            $pcount = 0
            if ($params) { $pcount = ($params -split ',').Count }
            [void]$targets.Add("$($f.BaseName):$mname`:$pcount")
        }
        elseif ($sig -match '(?:public|private|protected|internal)[\w<>\[\], ]*\s+([\w<>]+)\s*(?:=>|\{)') {
            [void]$targets.Add("$($f.BaseName):get_$($Matches[1])`:0")
        }
        else { $unparsed++ }
    }
}

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine("// <auto-generated> 由 gen-patch-targets.ps1 生成 — 引用 UnityEngine.Input 的 Assembly-CSharp 方法清单 </auto-generated>")
[void]$sb.AppendLine("namespace GamepadPoc")
[void]$sb.AppendLine("{")
[void]$sb.AppendLine("    public static partial class PatchTargets")
[void]$sb.AppendLine("    {")
[void]$sb.AppendLine("        // 格式: 类型名:方法名:参数个数（属性 getter 记作 get_属性名:0）")
[void]$sb.AppendLine("        public static readonly string[] AssemblyCSharp = new string[]")
[void]$sb.AppendLine("        {")
foreach ($t in $targets) { [void]$sb.AppendLine('            "' + $t + '",') }
[void]$sb.AppendLine("        };")
[void]$sb.AppendLine("    }")
[void]$sb.AppendLine("}")
[System.IO.File]::WriteAllText($outFile, $sb.ToString(), [System.Text.UTF8Encoding]::new($true))
Write-Host ("目标方法: " + $targets.Count + "  解析失败: " + $unparsed)
Write-Host ("已写入: " + $outFile)
